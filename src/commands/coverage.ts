/**
 * `dialecte coverage` — generate COMPLETE, config-driven type-coverage probes:
 *   • coverage.surface.generated.ts — type fan-out over every element × per-element generic
 *   • coverage.calls.generated.ts   — valid calls for every core verb × every (parent,child) edge
 *   • coverage.deep.generated.ts    — deepest-path nested getTree/findDescendants (recursion cost)
 * Dialect-agnostic; driven by the resolved DialecteConfig (binding + constantsDir + out).
 * Also exports `genNarrowing` (used by the `narrowing` gate) + `loadSchema` (shared schema loader).
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

import { refsOf } from '../lib/binding-refs.ts'
import { resolveTargets, tsconfigOf, type Binding } from '../lib/config.ts'
import { discoverMethodPaths } from '../lib/discover.ts'
import { discoveryEntry } from '../lib/discovery-entry.ts'
import { formatFiles, formatOptsFromArgv } from '../lib/format.ts'
import { ELEMENT_GENERICS } from './coverage.constants.ts'

import type { AttributeDetail, DialecteSchema } from './coverage.types.ts'
import type { DataType } from '@dialecte/core'

export function attributeValue(detail: AttributeDetail | undefined): string {
	if (detail?.fixed) return detail.fixed
	const enumeration = enumerated(detail?.type)?.filter((value) => value !== '')
	return enumeration?.length ? enumeration[0] : 'x'
}

/**
 * The values a datatype enumerates - its own, else its union members' -, as the generated attribute types list
 * them. A qualified name's values are written `{uri}local`, never what a document holds: none.
 */
function enumerated(datatype: DataType | undefined): readonly string[] | undefined {
	if (datatype === undefined || holdsQualifiedNames(datatype)) return undefined
	if (datatype.facets?.enumeration !== undefined) return datatype.facets.enumeration
	const members = ('union' in datatype ? datatype.union : []).flatMap(
		(member) => enumerated(member) ?? [],
	)
	return members.length > 0 ? [...new Set(members)] : undefined
}

function holdsQualifiedNames(datatype: DataType): boolean {
	if ('builtin' in datatype) return datatype.builtin === 'QName' || datatype.builtin === 'NOTATION'
	if ('list' in datatype) return holdsQualifiedNames(datatype.list)
	return datatype.union.some(holdsQualifiedNames)
}

export function genSurface(binding: Binding): string {
	const refs = refsOf(binding)
	const lines = [
		`// AUTO-GENERATED by \`dialecte coverage\` — do not edit. Complete per-element TYPE coverage.`,
		...refs.imports,
		'',
	]
	const names: string[] = []
	for (const generic of ELEMENT_GENERICS) {
		lines.push(
			`type All_${generic} = { [E in ${refs.elementsOf}]: ${refs.generic(generic, 'E')} }[${refs.elementsOf}]`,
		)
		names.push(`All_${generic}`)
	}
	lines.push('', `export type CoverageSurface = [${names.join(', ')}]`, '')
	return lines.join('\n')
}

export function genCalls(params: { schema: DialecteSchema; binding: Binding }): string {
	const { schema, binding } = params
	const refs = refsOf(binding)
	const childCap = Number(process.env.COVERAGE_CHILD_CAP || Infinity)
	const singletons = new Set(schema.singletons)
	function ref(element: string) {
		return singletons.has(element)
			? `{ tagName: '${element}' }`
			: `{ tagName: '${element}', id: 'x' }`
	}
	function details(element: string) {
		return schema.definition[element]?.attributes?.details ?? {}
	}
	function attributesObject(element: string) {
		const elementDetails = details(element)
		const required = Object.keys(elementDetails).filter((name) => elementDetails[name]?.required)
		return required.length
			? `{ ${required.map((name) => `'${name}': '${attributeValue(elementDetails[name])}'`).join(', ')} }`
			: '{}'
	}
	const lines = [
		`// AUTO-GENERATED by \`dialecte coverage\` — do not edit. Complete valid-call coverage (core verbs × schema).`,
		...refs.imports,
		`declare const q: ${refs.query}`,
		`declare const tx: ${refs.transaction}`,
		'',
		`export async function _coverageCalls() {`,
	]
	for (const element of schema.elements) {
		const elementRef = ref(element)
		lines.push(`\tawait q.getRecordsByTagName('${element}')`)
		lines.push(`\tawait q.getRecord(${elementRef})`)
		lines.push(`\tawait q.getAttributes(${elementRef})`)
		lines.push(`\tawait q.getAttributes(${elementRef}, { fullObject: true })`)
		lines.push(`\tawait q.getTree(${elementRef})`)
		lines.push(`\tawait q.findDescendants(${elementRef})`)
		lines.push(`\tawait tx.update(${elementRef}, { attributes: {} })`)
		lines.push(`\tawait tx.delete(${elementRef})`)
		const names = Object.keys(details(element))
		if (names.length) lines.push(`\tawait q.getAttribute(${elementRef}, { name: '${names[0]}' })`)
		for (const child of (schema.children[element] ?? []).slice(0, childCap)) {
			lines.push(`\tawait q.getChild(${elementRef}, '${child}')`)
			lines.push(`\tawait q.getChildren(${elementRef}, '${child}')`)
			lines.push(
				`\tawait tx.addChild(${elementRef}, { tagName: '${child}', attributes: ${attributesObject(child)} })`,
			)
			lines.push(
				`\tawait tx.ensureChild(${elementRef}, { tagName: '${child}', attributes: ${attributesObject(child)} })`,
			)
		}
	}
	lines.push('}', '')
	return lines.join('\n')
}

/** A trivial import-baseline file (auto-generated, so it's never hand-maintained). */
export function genBaseline(binding: Binding): string {
	const refs = refsOf(binding)
	return [
		`// AUTO-GENERATED by \`dialecte coverage\` — do not edit. Import baseline for bench subtraction.`,
		...refs.imports,
		'',
		`export type _Element = ${refs.elementsOf}`,
		'',
	].join('\n')
}

/** Greedy deepest acyclic child-path from `root`, preferring high-fan-out children (depth-capped). */
export function deepestPath(params: {
	root: string
	children: Record<string, readonly string[]>
	cap?: number
}): string[] {
	const { root, children, cap = 8 } = params
	const visited = new Set<string>()
	const path: string[] = []
	let current: string | undefined = root
	while (current && path.length < cap && !visited.has(current)) {
		path.push(current)
		visited.add(current)
		const kids: string[] = (children[current] ?? []).filter((child) => !visited.has(child))
		current = [...kids].sort(
			(left, right) => (children[right]?.length ?? 0) - (children[left]?.length ?? 0),
		)[0]
	}
	return path
}

function nestedSelect(tags: string[]): string {
	return tags.length ? `{ ${tags[0]}: ${nestedSelect(tags.slice(1))} }` : 'true'
}

/** Deepest-path nested getTree/findDescendants — exercises the recursive TreeSelect/collect cost. */
export function genDeepProbe(params: { schema: DialecteSchema; binding: Binding }): string {
	const { schema, binding } = params
	const refs = refsOf(binding)
	const singletons = new Set(schema.singletons)
	const root = schema.root ?? schema.singletons[0] ?? schema.elements[0]
	const rootRef = singletons.has(root)
		? `{ tagName: '${root}' }`
		: `{ tagName: '${root}', id: 'x' }`
	const path = deepestPath({ root, children: schema.children })
	const nested = nestedSelect(path.slice(1))
	const lines = [
		`// AUTO-GENERATED by \`dialecte coverage\` — do not edit. Deepest-path recursion probe.`,
		...refs.imports,
		`declare const q: ${refs.query}`,
		'',
		`export async function _coverageDeep() {`,
	]
	if (path.length > 1) {
		lines.push(`\tawait q.getTree(${rootRef}, { select: ${nested} })`)
		lines.push(`\tawait q.findDescendants(${rootRef}, { collect: ${nested} })`)
	} else {
		lines.push(`\tawait q.getTree(${rootRef})`)
		lines.push(`\tawait q.findDescendants(${rootRef})`)
	}
	lines.push('}', '')
	return lines.join('\n')
}

/**
 * Full public method-surface probe — instantiates params + return of EVERY discovered method (core verbs
 * AND the extension/domain groups: history, reference, dataModel, template, cleanUp, presentation, …).
 * `methodPaths` come from `discoverMethodPaths`. `Parameters<…>[0]` + `Awaited<ReturnType<…>>` are forced
 * computations, so referencing them all in `CoverageApi` makes tsc instantiate the whole surface — what
 * `bench` measures as `coverage: api` and the `narrowing` gate type-checks. (A pure mapped-type fan-out
 * does NOT force instantiation — measured +131 — hence this explicit per-method form.)
 */
export function genApiProbe(params: { binding: Binding; methodPaths: readonly string[] }): string {
	const { binding, methodPaths } = params
	const refs = refsOf(binding)
	const lines = [
		`// AUTO-GENERATED by \`dialecte coverage\` — do not edit. Full method-surface instantiation (incl. extensions).`,
		...refs.imports,
		`declare const q: ${refs.query}`,
		`declare const tx: ${refs.transaction}`,
		`declare const doc: ${refs.nullary('Document')}`,
		`declare const project: ${refs.nullary('Project')}`,
		'',
	]
	const probeNames: string[] = []
	methodPaths.forEach((methodPath, index) => {
		// Whole Parameters tuple (not [0]) — instantiates every param AND avoids TS2493 on zero-arg methods.
		lines.push(`export type MP_${index} = Parameters<typeof ${methodPath}>`)
		lines.push(`export type MR_${index} = Awaited<ReturnType<typeof ${methodPath}>>`)
		probeNames.push(`MP_${index}`, `MR_${index}`)
	})
	lines.push('', `export type CoverageApi = [${probeNames.join(', ')}]`, '')
	return lines.join('\n')
}

/**
 * Exhaustive, schema-derived type-narrowing assertions (the IntelliSense safety net). Type-checked by
 * the `narrowing` gate; a false assertion is a TS error in this file. Portable across dialects + core:
 * uses only the guaranteed schema (elements/children/singletons/attrs) + structural namespace checks.
 */
export function genNarrowing(params: { schema: DialecteSchema; binding: Binding }): string {
	const { schema, binding } = params
	const refs = refsOf(binding)
	const singletons = new Set(schema.singletons)
	const lines: string[] = [
		`// AUTO-GENERATED by \`dialecte narrowing\` — do not edit. Exhaustive narrowing assertions.`,
		...refs.imports,
		'',
		`type Expect<T extends true> = T`,
		`type Equal<A, B> =`,
		`\t(<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false`,
		`type Includes<Member, Union> = Member extends Union ? true : false`,
		`type IdOptional<E extends ${refs.elementsOf}> = undefined extends ${refs.generic('Ref', 'E')}['id'] ? true : false`,
		'',
	]
	let assertionCount = 0
	function assertType(body: string) {
		lines.push(`type _${assertionCount++} = Expect<${body}>`)
	}

	// — global invariants —
	assertType(`Equal<Includes<string, ${refs.elementsOf}>, false>`) // element union not widened to string
	assertType(`Includes<${refs.generic('ParentsOf', refs.elementsOf)}, ${refs.elementsOf}>`) // all parents ⊆ elements
	assertType(`Includes<${refs.generic('DescendantsOf', refs.elementsOf)}, ${refs.elementsOf}>`) // all descendants ⊆ elements
	assertType(`Includes<'query', keyof ${refs.nullary('Document')}>`)
	assertType(`Includes<'transaction', keyof ${refs.nullary('Document')}>`)
	assertType(`Includes<'query', keyof ReturnType<${refs.nullary('Project')}['openDocument']>>`)
	if (schema.root) {
		assertType(`Equal<${refs.nullary('RootElementOf')}, '${schema.root}'>`)
		assertType(`Includes<'${schema.root}', ${refs.nullary('SingletonElementsOf')}>`)
	}
	for (const singleton of schema.singletons)
		assertType(`Includes<'${singleton}', ${refs.nullary('SingletonElementsOf')}>`)

	// — per element: membership, record tagName, Ref id-requiredness, first attribute —
	for (const element of schema.elements) {
		assertType(`Includes<'${element}', ${refs.elementsOf}>`)
		assertType(`Equal<${refs.generic('TrackedRecord', `'${element}'`)}['tagName'], '${element}'>`)
		assertType(`Equal<IdOptional<'${element}'>, ${singletons.has(element) ? 'true' : 'false'}>`)
		const attributeNames = Object.keys(schema.definition[element]?.attributes?.details ?? {})
		if (attributeNames.length)
			assertType(
				`Includes<'${attributeNames[0]}', ${refs.generic('AttributesOf', `'${element}'`)}>`,
			)
	}

	// — per child edge: child ∈ ChildrenOf<parent> —
	for (const [parent, kids] of Object.entries(schema.children))
		for (const child of kids)
			assertType(`Includes<'${child}', ${refs.generic('ChildrenOf', `'${parent}'`)}>`)

	lines.push('')
	return lines.join('\n')
}

/** Load + validate a dialect's leaf generated constants into a DialecteSchema. Shared by commands. */
export async function loadSchema(absConstantsDir: string): Promise<DialecteSchema> {
	const constantsPath = join(absConstantsDir, 'constants.generated.ts')
	const definitionPath = join(absConstantsDir, 'definition.generated.ts')
	for (const path of [constantsPath, definitionPath])
		if (!existsSync(path)) throw new Error(`expected ${path}`)
	// Import leaf generated files DIRECTLY (pure data) — Node's native TS strip handles them, no tsx.
	const mod: Record<string, unknown> = {
		...(await import(pathToFileURL(constantsPath).href)),
		...(await import(pathToFileURL(definitionPath).href)),
	}
	for (const exportName of ['ELEMENT_NAMES', 'CHILDREN', 'SINGLETON_ELEMENTS', 'DEFINITION'])
		if (!(exportName in mod))
			throw new Error(`${absConstantsDir} leaf files do not export ${exportName}`)
	return {
		elements: mod.ELEMENT_NAMES as string[],
		children: mod.CHILDREN as Record<string, readonly string[]>,
		singletons: mod.SINGLETON_ELEMENTS as string[],
		definition: mod.DEFINITION as never,
		root: typeof mod.ROOT_ELEMENT === 'string' ? mod.ROOT_ELEMENT : undefined,
	}
}

/** Write the probe files into `outDir`; returns the absolute paths written. */
export function generateCoverage(params: {
	schema: DialecteSchema
	binding: Binding
	outDir: string
	methodPaths?: readonly string[]
}): string[] {
	const { schema, binding, outDir, methodPaths } = params
	mkdirSync(outDir, { recursive: true })
	const written: [string, string][] = [
		[join(outDir, 'coverage.surface.generated.ts'), genSurface(binding)],
		[join(outDir, 'coverage.calls.generated.ts'), genCalls({ schema, binding })],
		[join(outDir, 'coverage.deep.generated.ts'), genDeepProbe({ schema, binding })],
		[join(outDir, 'baseline.ts'), genBaseline(binding)],
	]
	if (methodPaths)
		written.push([join(outDir, 'coverage.api.generated.ts'), genApiProbe({ binding, methodPaths })])
	for (const [path, content] of written) writeFileSync(path, content)
	const edges = Object.values(schema.children).reduce(
		(total, kids) => total + (kids?.length ?? 0),
		0,
	)
	console.log(`coverage: ${schema.elements.length} elements, ${edges} child edges → ${outDir}`)
	return written.map(([path]) => path)
}

export async function run(argv: string[]): Promise<void> {
	const targets = resolveTargets(argv)
	if (!targets.length)
		throw new Error(
			'coverage: no dialect versions discovered (src/<version>/definition/*.generated.ts). Pass --constants-dir, or add a "dialecte" config.',
		)
	const fmt = formatOptsFromArgv(argv)
	const tsconfig = tsconfigOf(argv)
	for (const target of targets) {
		const schema = await loadSchema(resolve(process.cwd(), target.constantsDir))
		console.log(`[${target.version}]`)
		// Discover the full method surface (incl. extension/domain groups) → the coverage.api probe.
		let methodPaths: string[] | undefined
		try {
			methodPaths = discoverMethodPaths({
				entrySource: discoveryEntry(target.binding),
				tsconfig,
				root: process.cwd(),
			})
		} catch {
			console.warn(
				`  ⚠ [${target.version}] method-surface discovery failed — skipping coverage.api probe`,
			)
		}
		const written = generateCoverage({
			schema,
			binding: target.binding,
			outDir: resolve(process.cwd(), target.outDir),
			methodPaths,
		})
		formatFiles({ root: process.cwd(), files: written, options: fmt })
	}
}
