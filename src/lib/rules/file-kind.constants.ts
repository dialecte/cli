/** A generated module: `x.generated.ts`. */
export const GENERATED_NAME_PATTERN = /\.generated\.[cm]?tsx?$/

/** A declaration file: `x.d.ts`. */
export const DECLARATION_NAME_PATTERN = /\.d\.[cm]?ts$/

/** A test or its support by name: `x.test.ts`, `x.spec.ts`, `x.cases.ts`, `x.fixtures.ts`. */
export const TEST_NAME_PATTERN = /\.(test|spec|cases|fixtures)\.[cm]?tsx?$/

/** The folder whose files are tests. */
export const TESTS_FOLDER = '__tests__'

/** A script file: any other name is text. */
export const SCRIPT_NAME_PATTERN = /\.[cm]?tsx?$/

/** A types file: `x.types.ts`, `types.ts`, `type.ts`, `types.x.ts`. */
export const TYPES_NAME_PATTERN = /(^|\.)types?\./

/** The folder whose files hold types. */
export const TYPES_FOLDER = 'types'

/** A constants file: `x.constants.ts`, `constants.ts`, `constant.ts`, `constants.x.ts`. */
export const CONSTANTS_NAME_PATTERN = /(^|\.)constants?\./

/** The folder whose files hold module constants. */
export const CONSTANTS_FOLDER = 'constants'

/** A configuration file: `x.config.ts`. */
export const CONFIG_NAME_PATTERN = /\.config\.[cm]?tsx?$/

/** The folder of a skill that holds eval fixtures: `skills/<skill>/evals/`. */
export const EVALS_FOLDER = 'evals'
